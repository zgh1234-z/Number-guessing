const x = 2;
let i;

while (i != x) {
  let i = Number(prompt("یک عدد بین 0 تا 10 حدس بزن "));

  if (i <= 0 || i >= 10) {
    alert("عدد باید بین 0 تا 10 باشد ");
  } else {
    if (i == x) {
      alert("درست حدس زدید ");
      break;
    } else if (i > x) {
      alert("حدس شما بزرگ تر از عدد مورد نظر  دوباره امتحان کنید ");
    } else {
      alert("حدس شما کوچک تر از عدد مورد نظر دوباره امتحان کنید ");
    }
  }
}
